"""Generate firmware catalogue artefacts from catalog/catalog.json.

Outputs:
  firmware/.../Catalog.gen.h  - numeric channel table (PROGMEM) + /api/meta JSON (PROGMEM)
  web/src/catalog.gen.json    - same meta document, used by the dashboard's demo mode

Usage: python3 tools/gen_catalog.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "catalog" / "catalog.json"
FW = ROOT / "firmware/OpenInverterGateway/SRC/ShineWiFi-ModBus/Catalog.gen.h"
WEB = ROOT / "web/src/catalog.gen.json"

TYPES = {"u16": 0, "s16": 1, "u32": 2, "s32": 3, "lo8": 4, "hi8": 5}
REG_BASE, REG_COUNT = 3000, 125
# Registers 3000..3044 change every second (power, PV, AC); the rest are
# counters and diagnostics that are polled less often.
FAST_LAST = 3044


def flt(x):
    """C++ float literal (1 -> 1.0f, 0.1 -> 0.1f)."""
    r = repr(float(x))
    return r + "f"


def main():
    cat = json.loads(SRC.read_text())
    chans = cat["channels"]
    ids = [c["id"] for c in chans]
    assert len(ids) == len(set(ids)), "duplicate channel id"
    for c in chans:
        assert c["type"] in TYPES, c
        assert REG_BASE <= c["reg"] < REG_BASE + REG_COUNT, c
        width = 2 if c["type"] in ("u32", "s32") else 1
        assert c["reg"] + width - 1 < REG_BASE + REG_COUNT, c

    h1 = [c for c in chans if c.get("h1") is not None]
    # 15-minute tier: means of all h1 channels, max of pac, last of day counters
    h15 = [(c["id"], "mean", c["h1"]) for c in h1]
    h15.append(("pac", "max", 1))
    h15 += [(c["id"], "last", c["h15"]) for c in chans if c.get("agg15") == "last"]
    assert len(h1) <= 32 and len(h15) <= 40

    idx = {cid: i for i, cid in enumerate(ids)}
    meta = {
        "categories": cat["categories"],
        "channels": [
            {k: c[k] for k in ("id", "name", "unit", "cat", "reg", "type", "scale",
                               "kind", "quality", "desc") if k in c}
            | ({"mppt": c["mppt"]} if "mppt" in c else {})
            for c in chans
        ],
        "tiers": {
            "h1": {"interval": 60, "channels": [c["id"] for c in h1],
                   "scale": [c["h1"] for c in h1]},
            "h15": {"interval": 900, "channels": [f"{cid}:{agg}" for cid, agg, _ in h15],
                    "scale": [s for _, _, s in h15]},
        },
    }
    meta_json = json.dumps(meta, separators=(",", ":"), ensure_ascii=False)

    lines = [
        "// GENERATED by tools/gen_catalog.py from catalog/catalog.json - do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define CAT_REG_BASE {REG_BASE}",
        f"#define CAT_REG_COUNT {REG_COUNT}",
        f"#define CAT_FAST_LAST {FAST_LAST}",
        f"#define CAT_CHANNELS {len(chans)}",
        f"#define CAT_H1 {len(h1)}",
        f"#define CAT_H15 {len(h15)}",
        "",
        "enum CatType : uint8_t { CT_U16, CT_S16, CT_U32, CT_S32, CT_LO8, CT_HI8 };",
        "enum CatAgg : uint8_t { CA_MEAN, CA_MAX, CA_LAST };",
        "",
        "struct CatChannel {",
        "  uint16_t reg;     // input register (function 4)",
        "  uint8_t type;     // CatType",
        "  float scale;      // engineering value = raw * scale",
        "};",
        "",
        "// channel index constants",
    ]
    lines += [f"#define CH_{cid.upper()} {i}" for i, cid in enumerate(ids)]
    lines += ["", "static const CatChannel kCatalog[CAT_CHANNELS] = {"]
    lines += [f"  {{{c['reg']}, CT_{c['type'].upper()}, {flt(c['scale'])}}},  // {c['id']}" for c in chans]
    lines += ["};", "", "struct TierChannel {", "  uint8_t ch;      // index into kCatalog",
              "  uint8_t agg;     // CatAgg", "  float scale;     // stored int16 * scale = value", "};", ""]
    lines += ["static const TierChannel kTierH1[CAT_H1] = {"]
    lines += [f"  {{CH_{c['id'].upper()}, CA_MEAN, {flt(c['h1'])}}}," for c in h1]
    lines += ["};", "", "static const TierChannel kTierH15[CAT_H15] = {"]
    lines += [f"  {{CH_{cid.upper()}, CA_{agg.upper()}, {flt(s)}}}," for cid, agg, s in h15]
    lines += ["};", ""]
    esc = meta_json.replace("\\", "\\\\").replace('"', '\\"')
    lines += ["#ifdef ARDUINO", "#include <pgmspace.h>",
              f'static const char kMetaJson[] PROGMEM = "{esc}";', "#endif", ""]
    FW.write_text("\n".join(lines))
    WEB.parent.mkdir(parents=True, exist_ok=True)
    WEB.write_text(json.dumps(meta, indent=1, ensure_ascii=False))
    print(f"{len(chans)} channels, h1={len(h1)}, h15={len(h15)}, meta {len(meta_json.encode())} B")


if __name__ == "__main__":
    main()

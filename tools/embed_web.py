"""Gzip the built dashboard and embed it as a PROGMEM array.

Usage: python3 tools/embed_web.py [web/dist/index.html]
Writes firmware/.../WebUi.gen.h with kWebUi, kWebUiLen and an ETag.
"""
import gzip
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "web/dist/index.html"
out = ROOT / "firmware/OpenInverterGateway/SRC/ShineWiFi-ModBus/WebUi.gen.h"

html = src.read_bytes()
gz = gzip.compress(html, compresslevel=9, mtime=0)
etag = hashlib.sha1(gz).hexdigest()[:16]
rows = [", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]

lines = [
    "// GENERATED by tools/embed_web.py - do not edit.",
    "#pragma once",
    "#include <pgmspace.h>",
    "",
    f"// {src.name}: {len(html)} bytes raw, {len(gz)} bytes gzip",
    f'static const char kWebUiEtag[] PROGMEM = "\\"{etag}\\"";',
    f"static const uint32_t kWebUiLen = {len(gz)};",
    "static const uint8_t kWebUi[] PROGMEM = {",
    "  " + ",\n  ".join(rows),
    "};",
    "",
]
out.write_text("\n".join(lines))
print(f"{src.name}: {len(html)} B raw -> {len(gz)} B gzip, etag {etag}")
